// bootRecovery implements the §F4 crash rules: a candidate/ present at
// boot is discarded, live/ is re-rendered from the committed config,
// and an interrupted transaction is finished-from-committed or rolled
// back — never left half-applied.
func bootRecovery() {
	if phase := store.getTxPhase(); phase != "" && phase != "committed" && phase != "rolledback" {
		log.Printf("boot recovery: transaction interrupted in phase %q — discarding candidate, booting committed config", phase)
	}
	_ = os.RemoveAll(candidateDir)
	_ = os.MkdirAll(candidateDir, 0o755)
	_ = os.MkdirAll(liveDir, 0o755)
	renderLiveFromCommitted()
	store.setTxPhase("")
}

// renderLiveFromCommitted regenerates live/ (wpa_supplicant.conf,
// wg-hsl.conf) from the committed wifi.conf / vpn.conf.
func renderLiveFromCommitted() {
	if b, err := os.ReadFile(wifiPath); err == nil {
		_ = writeFileAtomic(wpaLiveConfig, b, 0o600)
	}
	if v, err := loadVPN(); err == nil && v.Type == "wireguard" {
		_ = writeFileAtomic(wgConfigPath, []byte(v.Conf), 0o600)
	}
}

func main() {
	log.SetFlags(log.LstdFlags | log.Lmicroseconds)
	log.SetPrefix("") // journald adds the unit/tag (SyslogIdentifier=hsl-provisiond)
	identity = loadIdentity()
	store.load()
	bootRecovery()
	log.Printf("hsl-provisiond %s starting serial_last4=%s model=%q", fwVersion, last4(identity.Serial), modelName)

	// Kill switch (§F4): the merged ruleset is loaded by nftables.service
	// from /etc/nftables.conf before provisiond starts. If it is missing
	// here the failure is LOUD and VPN raise stays blocked — never a
	// log-and-continue into an unprotected state (F5).
	if err := applyKillSwitch(); err != nil {
		log.Printf("FATAL: nftables kill switch not in place: %v — vpn raise blocked, retrying in background", err)
		go func() {
			for {
				time.Sleep(30 * time.Second)
				if err := applyKillSwitch(); err == nil {
					log.Printf("kill switch applied on retry")
					return
				}
			}
		}()
	}

	go btSupervision()
	go provisioningWindowManager()
	go apFallbackServer()

	gatt, err := startGATT()
	if err != nil {
		log.Printf("GATT server failed to start: %v (daemon continues; AP fallback remains)", err)
	} else {
		defer gatt.Close()
	}

	// If a committed config exists, bring the link/VPN back up.
	if hasWifiConfig() {
		go func() {
			if err := joinStoredWifi(); err != nil {
				log.Printf("stored wifi rejoin failed: %v", err)
				return
			}
			checkCaptiveAndVPN()
		}()
	} else {
		store.set("idle", "")
	}

	select {} // serve forever; systemd owns lifecycle
}
