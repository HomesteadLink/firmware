// fingerprint is the only permitted log representation of a secret:
// length + first 4 bytes of its SHA-256. Values are never logged.
func fingerprint(label, secret string) {
	sum := sha256.Sum256([]byte(secret))
	log.Printf("%s received len=%d sha256[0:4]=%s", label, len(secret), hex.EncodeToString(sum[:4]))
}

// --- Identity (§F1, updated: board serial, write-once per board) ---

type Identity struct {
	Serial    string `json:"serial"`
	SetupCode string `json:"setup_code"`
	// APPassphrase is an INDEPENDENT high-entropy per-device secret
	// (R3-3): generated by hsl-firstboot from /dev/urandom, persisted
	// here, cryptographically unrelated to the setup code and never
	// derived from the serial. The daemon only preserves it.
	APPassphrase string `json:"ap_passphrase,omitempty"`
}

// boardSerial is the H618 SoC serial from the device tree. arm64
// /proc/cpuinfo has no Serial field; the SD CID and the hostname are
// NEVER serial sources (§F1).
func boardSerial() string {
	b, err := os.ReadFile("/proc/device-tree/serial-number")
	if err != nil {
		return ""
	}
	return strings.Trim(strings.TrimSpace(string(b)), "\x00")
}

func loadDeviceSecret() ([]byte, error) {
	if b, err := os.ReadFile(deviceSecretPath); err == nil && len(b) >= 16 {
		return b, nil
	}
	secret := make([]byte, 32)
	if _, err := rand.Read(secret); err != nil {
		return nil, err
	}
	if err := writeFileAtomic(deviceSecretPath, secret, 0o600); err != nil {
		return nil, err
	}
	return secret, nil
}

// setupCodeFor is the §F1 derivation: full HMAC-SHA256(secret, serial)
// digest interpreted as an integer, mod 10^6, zero-padded to 6 digits.
func setupCodeFor(secret []byte, serial string) string {
	mac := hmac.New(sha256.New, secret)
	mac.Write([]byte(serial))
	n := new(big.Int).SetBytes(mac.Sum(nil))
	n.Mod(n, big.NewInt(1000000))
	s := n.String()
	for len(s) < 6 {
		s = "0" + s
	}
	return s
}

// loadIdentity implements updated §F1: identity follows the BOARD.
// identity.json is regenerated whenever the board serial differs from
// the stored one (a cloned card takes the new board's identity); with
// no board serial, a persisted random 128-bit value is the serial and
// is never re-derived. The image contains no secret of any kind.
func loadIdentity() Identity {
	stored := Identity{}
	if b, err := os.ReadFile(identityPath); err == nil {
		_ = json.Unmarshal(b, &stored)
	}
	serial := boardSerial()
	if serial == "" {
		serial = stored.Serial
	}
	if serial == "" {
		raw := make([]byte, 16) // random 128-bit fallback, generated once
		if _, err := rand.Read(raw); err == nil {
			serial = hex.EncodeToString(raw)
		}
	}
	secret, err := loadDeviceSecret()
	if err != nil {
		log.Printf("identity: device secret unavailable: %v", err)
		return Identity{Serial: serial, SetupCode: stored.SetupCode}
	}
	id := Identity{Serial: serial, SetupCode: setupCodeFor(secret, serial), APPassphrase: stored.APPassphrase}
	if stored.Serial != id.Serial || stored.SetupCode != id.SetupCode || stored.APPassphrase != id.APPassphrase {
		if b, err := json.Marshal(id); err == nil {
			_ = writeFileAtomic(identityPath, append(b, '\n'), 0o600)
		}
	}
	return id
}

func last4(s string) string {
	if len(s) <= 4 {
		return s
	}
	return s[len(s)-4:]
}

// --- State (§F4 Status characteristic schema) + persisted extras ---

type State struct {
	State string `json:"state"`
	Error string `json:"error"`
	SSID  string `json:"ssid"`
	IP4   string `json:"ip4"`
	VPN   bool   `json:"vpn"`
}

// MarshalJSON renders the contract Status shape: error, ssid and ip4
// are null (not "") until set, and vpn is a boolean.
func (st State) MarshalJSON() ([]byte, error) {
	nullable := func(v string) interface{} {
		if v == "" {
			return nil
		}
		return v
	}
	return json.Marshal(map[string]interface{}{
		"state": st.State,
		"error": nullable(st.Error),
		"ssid":  nullable(st.SSID),
		"ip4":   nullable(st.IP4),
		"vpn":   st.VPN,
	})
}

func (st *State) UnmarshalJSON(b []byte) error {
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(b, &raw); err != nil {
		return err
	}
	str := func(k string) string {
		var v string
		_ = json.Unmarshal(raw[k], &v)
		return v
	}
	st.State, st.Error, st.SSID, st.IP4 = str("state"), str("error"), str("ssid"), str("ip4")
	var vb bool
	if err := json.Unmarshal(raw["vpn"], &vb); err == nil {
		st.VPN = vb
	} else {
		st.VPN = str("vpn") != ""
	}
	return nil
}

// lockoutState is the §F4 pairing lockout, persisted in state.json.
type lockoutState struct {
	FailCount    int   `json:"fail_count"`
	LockoutCount int   `json:"lockout_count"`
	LockedUntil  int64 `json:"locked_until_unix"`
}

// persistedState is the state.json document: the Status value plus the
// lockout counters and the in-flight transaction phase (§F4 crash rules).
type persistedState struct {
	Status  State        `json:"status"`
	Lockout lockoutState `json:"lockout"`
	TxPhase string       `json:"tx_phase"`
}

type stateStore struct {
	mu       sync.Mutex
	st       State
	lk       lockoutState
	txPhase  string
	onChange func(State)
}

func (s *stateStore) set(state, errStr string) {
	s.mu.Lock()
	s.st.State = state
	s.st.Error = errStr
	st := s.st
	s.mu.Unlock()
	s.persist()
	if s.onChange != nil {
		s.onChange(st)
	}
	log.Printf("state=%s error=%q ssid=%q ip4=%q vpn=%v", st.State, st.Error, st.SSID, st.IP4, st.VPN)
}

func (s *stateStore) update(fn func(*State)) {
	s.mu.Lock()
	fn(&s.st)
	st := s.st
	s.mu.Unlock()
	s.persist()
	if s.onChange != nil {
		s.onChange(st)
	}
}

func (s *stateStore) get() State {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.st
}

func (s *stateStore) setTxPhase(phase string) {
	s.mu.Lock()
	s.txPhase = phase
	s.mu.Unlock()
	s.persist()
}

func (s *stateStore) getTxPhase() string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.txPhase
}

// json renders Status ≤128 B. On overflow the SSID is shortened FIRST;
// the error code is never dropped (F15).
func (s *stateStore) json() []byte {
	st := s.get()
	b, _ := json.Marshal(st)
	for len(b) > 128 && len(st.SSID) > 0 {
		st.SSID = st.SSID[:len(st.SSID)-1]
		b, _ = json.Marshal(st)
	}
	if len(b) > 128 { // last resort: drop ssid, keep state+error
		st.SSID = ""
		b, _ = json.Marshal(st)
	}
	return b
}

// persist writes state.json atomically: tmp + fsync + rename + dir fsync.
func (s *stateStore) persist() {
	s.mu.Lock()
	doc := persistedState{Status: s.st, Lockout: s.lk, TxPhase: s.txPhase}
	s.mu.Unlock()
	b, err := json.Marshal(doc)
	if err != nil {
		return
	}
	if err := os.MkdirAll(cfgDir, 0o755); err != nil {
		return
	}
	tmp := statePath + ".tmp"
	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return
	}
	if _, err := f.Write(b); err != nil {
		f.Close()
		return
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return
	}
	f.Close()
	if err := os.Rename(tmp, statePath); err != nil {
		return
	}
	if d, err := os.Open(cfgDir); err == nil {
		d.Sync()
		d.Close()
	}
}

func (s *stateStore) load() {
	b, err := os.ReadFile(statePath)
	if err != nil {
		s.st = State{State: "idle"}
		return
	}
	var doc persistedState
	if err := json.Unmarshal(b, &doc); err == nil && doc.Status.State != "" {
		s.st, s.lk, s.txPhase = doc.Status, doc.Lockout, doc.TxPhase
		return
	}
	// Legacy shape: state.json was the bare Status object.
	var st State
	if err := json.Unmarshal(b, &st); err == nil && st.State != "" {
		s.st = st
		return
	}
	s.st = State{State: "idle"}
}

func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, perm); err != nil {
		return err
	}
	if f, err := os.OpenFile(tmp, os.O_RDWR, perm); err == nil {
		f.Sync()
		f.Close()
	}
	return os.Rename(tmp, path)
}

func hasWifiConfig() bool {
	_, err := os.Stat(wifiPath)
	return err == nil
}

// --- Wi-Fi/VPN transaction gate (§F4: one transaction at a time) ---

var txMu sync.Mutex
var txActive bool

func beginTx() bool {
	txMu.Lock()
	defer txMu.Unlock()
	if txActive {
		return false
	}
	txActive = true
	return true
}

func endTx() {
	txMu.Lock()
	txActive = false
	txMu.Unlock()
}

func isTxActive() bool {
	txMu.Lock()
	defer txMu.Unlock()
	return txActive
}

